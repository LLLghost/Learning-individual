#!/usr/bin/env python3
"""Fixed course recipes. Run only inside a dedicated, explicitly enrolled lab guest."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import secrets
import selectors
import signal
import subprocess
import sys
import time

EMBEDDED = None  # BUILD_CATALOG
BASE = Path('/var/lib/mayak-practice')
MARKER = Path('/etc/mayak-practice-guest')


def digest(value):
    return hashlib.sha256(value).hexdigest()


def load_catalog():
    if EMBEDDED is not None:
        return EMBEDDED
    return json.loads(Path(__file__).with_name('catalog.json').read_text())


def atomic(path, value):
    temporary = path.with_suffix('.tmp')
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')
    os.replace(temporary, path)


def checked_root(lesson):
    if BASE.is_symlink() or any(p.is_symlink() for p in BASE.parents):
        raise ValueError('Symlink in practice root')
    path = BASE / lesson
    if path.is_symlink() or path.resolve().parent != BASE:
        raise ValueError('Unsafe practice path')
    return path


def execute(script, path, state, timeout=60):
    env = {**os.environ, 'WORK': str(path / 'work'), 'STATE': str(path),
           'NS': 'mk' + state['attempt'][:10], 'VARIANT': str(state['variant']),
           'COURSE_USER': state['user'], 'PORT': str(state.get('port',18080+state['variant'])), 'LC_ALL': 'C.UTF-8', 'HOME': '/root'}
    # Only scripts from the packaged catalog are executable; no submitted commands.
    process = subprocess.Popen(['bash', '-euo', 'pipefail', '-c', script],
                               env=env, cwd=path, stdout=subprocess.PIPE,
                               stderr=subprocess.PIPE, text=True, start_new_session=True)
    def stop():
        try: os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError: pass
        process.wait()
    chunks = {'out': bytearray(), 'err': bytearray()}
    deadline = time.monotonic()+timeout
    limited = False
    try:
        with selectors.DefaultSelector() as selector:
            selector.register(process.stdout, selectors.EVENT_READ, 'out')
            selector.register(process.stderr, selectors.EVENT_READ, 'err')
            while selector.get_map():
                remaining = deadline-time.monotonic()
                if remaining <= 0:
                    stop()
                    raise subprocess.TimeoutExpired(process.args, timeout)
                for key,_ in selector.select(min(remaining, .2)):
                    data = os.read(key.fileobj.fileno(), 65536)
                    if not data:
                        selector.unregister(key.fileobj)
                        continue
                    buffer = chunks[key.data]
                    capacity = 1024*1024-len(buffer)
                    buffer.extend(data[:capacity])
                    if len(data)>capacity:
                        limited=True
                        stop()
                        break
                if limited: break
        if not limited:
            try: process.wait(timeout=max(.01,deadline-time.monotonic()))
            except subprocess.TimeoutExpired:
                stop()
                raise
    finally:
        process.stdout.close()
        process.stderr.close()
    out,err=(chunks[k].decode('utf-8',errors='replace') for k in ('out','err'))
    if limited: err+='\nOUTPUT LIMIT: truncated after 1 MiB per stream; result rejected.\n'
    return subprocess.CompletedProcess(process.args, 125 if limited else process.returncode, out, err)


def main():
    catalog = load_catalog()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['list', 'enroll', 'prepare', 'check', 'restore', 'solve', 'status'])
    parser.add_argument('lesson', nargs='?', choices=list(catalog['labs']))
    parser.add_argument('--variant', type=int, choices=[0, 1], default=0)
    parser.add_argument('--user', default=os.environ.get('SUDO_USER', 'course'))
    parser.add_argument('--disposable-guest', action='store_true')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--attempt', help='32 hexadecimal characters generated by the course')
    args = parser.parse_args()
    if args.action == 'list':
        for lesson, lab in catalog['labs'].items():
            print(f"{lesson}: {lab['goal']}")
        return 0
    if platform.system() != 'Linux' or os.geteuid() != 0:
        raise ValueError('Use sudo inside the dedicated Linux lab guest')
    if args.action == 'enroll':
        if not args.disposable_guest or Path('/etc/pve').exists():
            raise ValueError('Enrollment requires --disposable-guest; Proxmox host is forbidden')
        if not MARKER.exists():
            MARKER.write_text(secrets.token_hex(16) + '\n')
            MARKER.chmod(0o600)
        print('Dedicated guest enrolled. Never enroll a workstation or production machine.')
        return 0
    if not MARKER.is_file() or MARKER.is_symlink() or Path('/etc/pve').exists():
        raise ValueError('Dedicated enrolled guest required; cannot run on the Proxmox host')
    if not args.lesson:
        parser.error('lesson is required')
    import pwd
    account = pwd.getpwnam(args.user)
    if account.pw_uid == 0:
        raise ValueError('The learner must be an unprivileged existing user')
    lab = catalog['labs'][args.lesson]
    path = checked_root(args.lesson)
    path.mkdir(parents=True, exist_ok=True)
    import fcntl
    lock = (path / 'operation.lock').open('a')
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    if (path / 'work').is_symlink():
        raise ValueError('Symlink work directory')
    for parent, dirs, files in os.walk(path / 'work', followlinks=False):
        if any((Path(parent) / name).is_symlink() for name in dirs + files):
            raise ValueError('Symlink in learner workspace; remove the link as the learner before continuing')
    state_file = path / 'state.json'
    if state_file.is_symlink():
        raise ValueError('Symlink state file')
    state = json.loads(state_file.read_text()) if state_file.exists() else None
    if args.action == 'status':
        print(json.dumps(state, ensure_ascii=False, indent=2))
        return 0
    if args.action == 'prepare':
        if state and state.get('active'):
            raise ValueError('Active attempt exists. Restore it before preparing another one.')
        missing = [c for c in lab['requires'] if subprocess.run(
            ['bash', '-c', 'command -v "$1" >/dev/null', '_', c]).returncode]
        if missing:
            raise ValueError('Missing prerequisites: ' + ', '.join(missing))
        if args.attempt and (len(args.attempt) != 32 or any(c not in '0123456789abcdef' for c in args.attempt)):
            raise ValueError('Invalid attempt identifier')
        state = {'attempt': args.attempt or secrets.token_hex(16), 'variant': args.variant,
                 'user': args.user, 'started': time.time(), 'active': True,
                 'port': 18080+args.variant, 'lesson': args.lesson, 'guest': digest(MARKER.read_bytes()),
                 'catalog': digest(json.dumps(catalog, sort_keys=True).encode())}
        atomic(state_file, state)  # Record ownership before creating resources; failed setup is restorable.
        (path / 'work').mkdir(exist_ok=True)
        os.chown(path / 'work', account.pw_uid, account.pw_gid)
        result = execute(lab['prepare'], path, state, lab.get('timeout', 120))
    else:
        if args.action == 'restore' and state and not state.get('active'):
            print('Already restored')
            return 0
        if not state or not state.get('active'):
            raise ValueError('No active attempt')
        if state['catalog'] != digest(json.dumps(catalog, sort_keys=True).encode()):
            raise ValueError('Use the same recipe version for this attempt, including restore')
        result = execute(lab[args.action], path, state, lab.get('timeout', 120))
    print(result.stdout, end='')
    if result.stderr:
        print(result.stderr, end='', file=sys.stderr)
    if args.action == 'check':
        report = {'schema': 'mayak-practice-report-v1', 'lesson': args.lesson,
                  'attempt': state['attempt'], 'variant': state['variant'],
                  'started': state['started'], 'checked': time.time(),
                  'runnerSha256': digest(Path(__file__).read_bytes()),
                  'catalogSha256': state['catalog'], 'guest': state['guest'],
                  'environment': {'kernel': platform.release(), 'host': platform.node()},
                  'passed': result.returncode == 0, 'observations': result.stdout,
                  'error': result.stderr}
        payload = json.dumps(report, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
        envelope = {'schema': 'mayak-practice-envelope-v1', 'payload': payload,
                    'sha256': digest(payload.encode())}
        atomic(path / 'latest-report.json', envelope)
        if args.output:
            target = args.output.absolute()
            if target.parent.resolve().stat().st_uid != account.pw_uid:
                raise ValueError('Choose an output directory owned by the learner')
            if target.exists() or target.is_symlink():
                raise ValueError('Report output exists; choose a new filename')
            # Exclusive creation avoids overwriting arbitrary files under sudo.
            with target.open('x') as stream:
                json.dump(envelope, stream, ensure_ascii=False, indent=2)
            os.chown(target, account.pw_uid, account.pw_gid)
        print('PASS' if report['passed'] else 'FAIL')
    if args.action == 'restore' and result.returncode == 0:
        state['active'] = False
        state['restored'] = time.time()
        atomic(state_file, state)
    return result.returncode


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError, subprocess.TimeoutExpired) as error:
        print(f'practice: {error}', file=sys.stderr)
        sys.exit(2)
